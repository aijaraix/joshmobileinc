test('Only the owner can soft-delete and restore a website request; a manager receives 403',async()=>{
 const owner='joshmobileinc@gmail.com',manager='sholom@aicreates.ai',token=randomBytes(32).toString('hex'),managerToken=randomBytes(32).toString('hex'),pass=randomBytes(22).toString('base64url');
 process.env.JM_SESSION_SECRET=randomBytes(48).toString('hex');
 process.env.JM_OWNER_INVITE_HASH=digest(token);process.env.JM_MANAGER_INVITE_HASH=digest(managerToken);
 process.env.JM_INVITE_EXPIRES=String(Date.now()+3600000);
 let r=await call(admin,'activate',{email:owner,token,password:pass});
 assert.equal(r.status,200);
 const ownerCookie=r.headers['set-cookie'].split(';')[0];
 r=await call(admin,'activate',{email:manager,token:managerToken,password:pass});assert.equal(r.status,200);const managerCookie=r.headers['set-cookie'].split(';')[0];
 const id=randomUUID(),customerId=randomUUID(),vehicleId=randomUUID(),reference='JM-ABCD2345',stamp=new Date().toISOString();
 await writeJson(customerPath(customerId),{id:customerId,name:'QA TEST',phone:'2025550142',status:'active',createdAt:stamp,updatedAt:stamp,version:1});
 await writeJson(vehiclePath(vehicleId),{id:vehicleId,customerId,year:'2018',make:'Honda',model:'Accord',vin:'1HGCM82633A004352',createdAt:stamp,updatedAt:stamp,version:1});
 await writeJson(jobPath(id),{id,reference,source:'website',customerId,vehicleId,createdAt:stamp,updatedAt:stamp,version:1,status:'requested',
 name:'QA TEST',address:'123 Example Street',city:'Pompano Beach',phone:'2025550142',media:[],attachments:[],timeline:[]});
 const body={id,version:1,confirmReference:reference};
 assert.equal((await call(admin,'trash',body)).status,401);
 assert.equal((await call(admin,'trash',body,ownerCookie,'POST','https://other.example')).status,403);
 assert.equal((await call(admin,'trash',body,managerCookie)).status,403);
 assert.equal((await call(admin,'trash',{...body,confirmReference:'JM-WRONG'},ownerCookie)).status,400);
 assert.equal((await call(booking,'',{},'','DELETE')).status,405);
 r=await call(admin,'trash',body,ownerCookie);
 assert.equal(r.status,200);
 const trashed=(await jobById(id)).value;assert(trashed.deletedAt);assert.equal(trashed.deletedBy,owner);
 assert(await readJson(customerPath(customerId)));assert(await readJson(vehiclePath(vehicleId)));assert(await jobById(id));
 assert.equal((await call(admin,'trash',body,ownerCookie)).status,409);
 assert.equal((await call(admin,'update',{...body,status:'confirmed'},ownerCookie)).status,409);
 r=await call(admin,'restore',{...body,version:trashed.version},ownerCookie);
 assert.equal(r.status,200);
 assert.equal((await jobById(id)).value.deletedAt,'');
 const manualId=randomUUID();await writeJson(jobPath(manualId),{id:manualId,reference:'JM-PPPP2222',source:'manual',version:1,createdAt:stamp,updatedAt:stamp,status:'requested'});
 assert.equal((await call(admin,'trash',{id:manualId,version:1,confirmReference:'JM-PPPP2222'},ownerCookie)).status,409);
 assert(await jobById(manualId));
});
